$$;

CREATE OR REPLACE FUNCTION public.prepare_status_update()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE official_name text;
BEGIN
  IF public.is_village_staff() THEN
    SELECT display_name INTO official_name FROM public.profiles WHERE id = auth.uid();
    NEW.updated_by := COALESCE(NULLIF(official_name, ''), 'Village Official');
  ELSE
    IF NEW.status <> 'pending' OR NOT EXISTS (
      SELECT 1 FROM public.complaints c
      WHERE c.id = NEW.complaint_id AND c.reporter_id = auth.uid() AND c.status = 'resolved'
    ) THEN
      RAISE EXCEPTION 'Only village officials can update complaints';
    END IF;
    NEW.updated_by := 'Citizen';
  END IF;
  NEW.updated_by_id := auth.uid();
  IF NEW.status = 'rejected' AND length(trim(COALESCE(NEW.note, ''))) = 0 THEN
    RAISE EXCEPTION 'A reason is required when rejecting a complaint';
  END IF;
  IF length(COALESCE(NEW.note, '')) > 2000 OR length(COALESCE(NEW.evidence_url, '')) > 2000000 THEN
    RAISE EXCEPTION 'Status note or evidence is too large';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_prepare_status_update ON public.status_updates;
CREATE TRIGGER trg_prepare_status_update BEFORE INSERT ON public.status_updates
FOR EACH ROW EXECUTE FUNCTION public.prepare_status_update();

CREATE OR REPLACE FUNCTION public.reopen_complaint(p_complaint_id integer, p_reason text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NOT public.account_is_active() THEN RAISE EXCEPTION 'Account is not active'; END IF;
  IF length(trim(COALESCE(p_reason, ''))) < 3 THEN RAISE EXCEPTION 'Please explain why this complaint needs to be reopened'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.complaints WHERE id = p_complaint_id AND reporter_id = auth.uid() AND status = 'resolved') THEN
    RAISE EXCEPTION 'Only your resolved complaints can be reopened';
  END IF;
  INSERT INTO public.status_updates (complaint_id, status, note, updated_by, updated_by_id)
  VALUES (p_complaint_id, 'pending', trim(p_reason), 'Citizen', auth.uid());
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_update_user(p_user_id uuid, p_role text DEFAULT NULL, p_blocked boolean DEFAULT NULL, p_is_active boolean DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NOT public.is_village_admin() THEN RAISE EXCEPTION 'Admin role required'; END IF;
  IF p_user_id = auth.uid() AND (p_role IS NOT NULL OR p_blocked = true OR p_is_active = false) THEN
    RAISE EXCEPTION 'You cannot remove your own administrative access';
  END IF;
  IF p_role IS NOT NULL AND p_role NOT IN ('citizen', 'sarpanch', 'admin') THEN RAISE EXCEPTION 'Invalid role'; END IF;
  UPDATE public.profiles SET
    role = COALESCE(p_role, role),
    blocked = COALESCE(p_blocked, blocked),
    is_active = COALESCE(p_is_active, is_active)
  WHERE id = p_user_id AND deleted_at IS NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'User account not found'; END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_soft_delete_user(p_user_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NOT public.is_village_admin() THEN RAISE EXCEPTION 'Admin role required'; END IF;
  IF p_user_id = auth.uid() THEN RAISE EXCEPTION 'You cannot delete your own account'; END IF;
  UPDATE public.profiles SET deleted_at = now(), is_active = false, blocked = true WHERE id = p_user_id AND deleted_at IS NULL;
  IF NOT FOUND THEN RAISE EXCEPTION 'User account not found'; END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_soft_delete_complaint(p_complaint_id integer)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NOT public.is_village_admin() THEN RAISE EXCEPTION 'Admin role required'; END IF;
