CREATE OR REPLACE FUNCTION public.set_complaint_owner()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NOT public.account_is_active() OR public.current_app_role() <> 'citizen' THEN
    RAISE EXCEPTION 'An active citizen account is required to submit a complaint';
  END IF;
  IF length(trim(COALESCE(NEW.title, ''))) NOT BETWEEN 3 AND 160 THEN RAISE EXCEPTION 'Complaint title must be 3 to 160 characters'; END IF;
  IF length(trim(COALESCE(NEW.description, ''))) NOT BETWEEN 5 AND 5000 THEN RAISE EXCEPTION 'Complaint description must be 5 to 5000 characters'; END IF;
  IF length(COALESCE(NEW.location, '')) > 300 THEN RAISE EXCEPTION 'Location must be 300 characters or less'; END IF;
  IF length(COALESCE(NEW.image_url, '')) > 2000000 THEN RAISE EXCEPTION 'Complaint image is too large'; END IF;
  NEW.reporter_id := auth.uid();
  SELECT display_name, phone INTO NEW.reporter_name, NEW.reporter_phone
  FROM public.profiles WHERE id = auth.uid();
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_set_complaint_owner ON public.complaints;
CREATE TRIGGER trg_set_complaint_owner BEFORE INSERT ON public.complaints
FOR EACH ROW EXECUTE FUNCTION public.set_complaint_owner();

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, display_name, role, email, phone)
  VALUES (NEW.id,
    COALESCE(NEW.raw_user_meta_data ->> 'display_name', NEW.raw_user_meta_data ->> 'full_name', ''),
    'citizen', NEW.email, COALESCE(NEW.raw_user_meta_data ->> 'phone', NEW.phone, ''))
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    phone = COALESCE(NULLIF(public.profiles.phone, ''), EXCLUDED.phone),
    display_name = COALESCE(NULLIF(public.profiles.display_name, ''), EXCLUDED.display_name);
  INSERT INTO public.notifications (recipient_id, title, body, kind, entity_id)
  SELECT id, 'New account registration', COALESCE(NULLIF(NEW.email, ''), 'A new village account was registered.'), 'account', NEW.id::text
  FROM public.profiles WHERE role = 'admin' AND id <> NEW.id AND blocked = false AND is_active = true AND deleted_at IS NULL;
  RETURN NEW;
END;
$$;

