END;
$$;

CREATE OR REPLACE FUNCTION public.audit_profile_changes()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE changed jsonb := '{}'::jsonb;
BEGIN
  IF TG_OP = 'UPDATE' AND (OLD.role IS DISTINCT FROM NEW.role OR OLD.blocked IS DISTINCT FROM NEW.blocked OR OLD.is_active IS DISTINCT FROM NEW.is_active OR OLD.deleted_at IS DISTINCT FROM NEW.deleted_at OR OLD.display_name IS DISTINCT FROM NEW.display_name OR OLD.phone IS DISTINCT FROM NEW.phone) THEN
    IF OLD.role IS DISTINCT FROM NEW.role THEN changed := changed || jsonb_build_object('role', jsonb_build_object('from', OLD.role, 'to', NEW.role)); END IF;
    IF OLD.blocked IS DISTINCT FROM NEW.blocked THEN changed := changed || jsonb_build_object('blocked', jsonb_build_object('from', OLD.blocked, 'to', NEW.blocked)); END IF;
    IF OLD.is_active IS DISTINCT FROM NEW.is_active THEN changed := changed || jsonb_build_object('is_active', jsonb_build_object('from', OLD.is_active, 'to', NEW.is_active)); END IF;
    IF OLD.deleted_at IS DISTINCT FROM NEW.deleted_at THEN changed := changed || jsonb_build_object('deleted', true); END IF;
    IF OLD.display_name IS DISTINCT FROM NEW.display_name THEN changed := changed || jsonb_build_object('display_name_changed', true); END IF;
    IF OLD.phone IS DISTINCT FROM NEW.phone THEN changed := changed || jsonb_build_object('phone_changed', true); END IF;
    INSERT INTO public.audit_logs (actor_id, action, subject_id, details)
    VALUES (auth.uid(), CASE WHEN OLD.role IS DISTINCT FROM NEW.role OR OLD.blocked IS DISTINCT FROM NEW.blocked OR OLD.is_active IS DISTINCT FROM NEW.is_active OR OLD.deleted_at IS DISTINCT FROM NEW.deleted_at THEN 'profile_access_changed' ELSE 'profile_details_updated' END, NEW.id::text, changed);
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_audit_profile_changes ON public.profiles;
CREATE TRIGGER trg_audit_profile_changes AFTER UPDATE ON public.profiles
FOR EACH ROW EXECUTE FUNCTION public.audit_profile_changes();

CREATE OR REPLACE FUNCTION public.notify_complaint_update()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
BEGIN
  IF NEW.reporter_id IS NOT NULL THEN
    INSERT INTO public.notifications (recipient_id, title, body, kind, entity_id)
    VALUES (NEW.reporter_id, 'Complaint status updated',
      'Your complaint ' || NEW.ticket_number || ' is now ' || replace(NEW.status, '_', ' ') ||
      CASE WHEN NEW.status = 'rejected' THEN ': ' || COALESCE((SELECT note FROM public.status_updates WHERE complaint_id = NEW.id ORDER BY created_at DESC LIMIT 1), '') ELSE '' END,
      'complaint', NEW.id::text);
  END IF;
  IF OLD.status = 'resolved' AND NEW.status = 'pending' THEN
    INSERT INTO public.notifications (recipient_id, title, body, kind, entity_id)
    SELECT id, 'Complaint reopened', NEW.ticket_number || ' was reopened by the citizen.', 'complaint', NEW.id::text
    FROM public.profiles WHERE role = 'sarpanch' AND blocked = false AND is_active = true AND deleted_at IS NULL;
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_notify_complaint_status ON public.complaints;
CREATE TRIGGER trg_notify_complaint_status AFTER UPDATE OF status ON public.complaints
FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION public.notify_complaint_update();

