CREATE OR REPLACE FUNCTION public.vote_in_poll(p_poll_id bigint, p_option_index smallint)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE poll_row public.village_polls%ROWTYPE;
BEGIN
  IF NOT public.account_is_active() OR public.current_app_role() <> 'citizen' THEN RAISE EXCEPTION 'Citizen account required'; END IF;
  SELECT * INTO poll_row FROM public.village_polls WHERE id = p_poll_id AND deleted_at IS NULL;
  IF NOT FOUND OR (poll_row.closes_at IS NOT NULL AND poll_row.closes_at <= now()) THEN RAISE EXCEPTION 'Poll is closed'; END IF;
  IF p_option_index < 0 OR p_option_index >= jsonb_array_length(poll_row.options) THEN RAISE EXCEPTION 'Invalid poll option'; END IF;
  INSERT INTO public.poll_votes (poll_id, voter_id, option_index) VALUES (p_poll_id, auth.uid(), p_option_index)
  ON CONFLICT (poll_id, voter_id) DO UPDATE SET option_index = EXCLUDED.option_index, created_at = now();
END;
$$;

CREATE OR REPLACE FUNCTION public.increment_complaint_upvote(p_complaint_id integer)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE next_count integer;
BEGIN
  IF NOT public.account_is_active() THEN RAISE EXCEPTION 'Active account required'; END IF;
  UPDATE public.complaints SET upvotes = upvotes + 1, updated_at = now()
  WHERE id = p_complaint_id AND deleted_at IS NULL
    AND (reporter_id = auth.uid() OR public.is_village_staff())
  RETURNING upvotes INTO next_count;
  IF next_count IS NULL THEN RAISE EXCEPTION 'Complaint not found'; END IF;
  RETURN next_count;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_village_metrics()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public
AS $$
DECLARE result jsonb;
BEGIN
  IF NOT public.is_village_staff() THEN RAISE EXCEPTION 'Village official role required'; END IF;
  SELECT jsonb_build_object(
    'citizens', (SELECT count(*) FROM public.profiles WHERE role = 'citizen' AND blocked = false AND is_active = true AND deleted_at IS NULL),
    'total', count(*),
    'pending', count(*) FILTER (WHERE status IN ('pending','under_review')),
    'in_progress', count(*) FILTER (WHERE status = 'in_progress'),
    'resolved', count(*) FILTER (WHERE status = 'resolved'),
    'resolution_percent', CASE WHEN count(*) = 0 THEN 0 ELSE round(100.0 * count(*) FILTER (WHERE status = 'resolved') / count(*), 1) END,
    'average_resolution_hours', round(avg(extract(epoch FROM (resolved_at - created_at)) / 3600) FILTER (WHERE resolved_at IS NOT NULL)::numeric, 1),
    'by_category', COALESCE((SELECT jsonb_object_agg(category, issue_count) FROM (SELECT category, count(*) issue_count FROM public.complaints WHERE deleted_at IS NULL GROUP BY category) categories), '{}'::jsonb),
    'monthly', COALESCE((SELECT jsonb_agg(jsonb_build_object('month', month, 'count', issue_count) ORDER BY month) FROM (SELECT date_trunc('month', created_at)::date AS month, count(*) issue_count FROM public.complaints WHERE deleted_at IS NULL AND created_at >= now() - interval '6 months' GROUP BY 1) months), '[]'::jsonb)
  ) INTO result FROM public.complaints WHERE deleted_at IS NULL;
  RETURN result;
END;
$$;

